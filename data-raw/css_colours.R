# Generate R/css_colours.R: the named colours of CSS, read from the table of
# the specification 'CSS Color Module Level 4' of the W3C. KaTeX writes the
# colours of \color, \textcolor, \colorbox and \fcolorbox as they are
# written in LaTeX, with their CSS meaning: some names are unknown to R
# ("teal", "lime"...) and others have another value in R ("green", "gray",
# "maroon", "purple" are X11 colours there).
#
#   source("data-raw/css_colours.R")

url <- "https://www.w3.org/TR/css-color-4/"
html <- xml2::read_html(url)
table <- xml2::xml_find_first(html, "//table[contains(@class, 'named-color-table')]")
rows <- xml2::xml_find_all(table, ".//tbody/tr")
name <- trimws(xml2::xml_text(xml2::xml_find_first(rows, ".//th")))
hex <- vapply(rows, function(row) {
  cells <- trimws(xml2::xml_text(xml2::xml_find_all(row, ".//td")))
  cells[grepl("^#[0-9a-fA-F]{6}$", cells)][1]
}, "")
stopifnot(length(name) == 148, !anyNA(hex), !anyDuplicated(name))
o <- order(name)

out <- c(
  "# Generated by data-raw/css_colours.R from the table of named colours of",
  "# the W3C specification 'CSS Color Module Level 4': do not edit by hand.",
  "",
  "# Named colours of CSS, as written by KaTeX (\\color, \\colorbox...).",
  "css_colours <- c(",
  paste0("  ", name[o], " = \"", toupper(hex[o]), "\"", c(rep(",", length(o) - 1), "")),
  ")"
)
writeLines(out, "R/css_colours.R", useBytes = TRUE)
