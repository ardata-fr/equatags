# Generate R/math_classes.R: the TeX class of the operators that KaTeX writes
# in <mo> elements, read from the table of symbols of KaTeX (src/symbols.js,
# calls defineSymbol(mode, font, group, char, name)), in the minified file
# shipped with the R package 'katex'. Run it again when 'katex' is updated:
#
#   source("data-raw/math_classes.R")
#
# Symbols of class "mathord" or "textord" are written by KaTeX in <mi>
# elements and are not kept. A character defined with several classes gets
# the first one of `priority`: the bars U+2223 and U+2225 are relations
# (\mid, \parallel) unless they are delimiters (see is_bar_delimiter()), and
# U+22C5 is a binary operator (\cdot) unless KaTeX marks it as a separator
# (\cdotp, see mo_class()).

priority <- c("rel", "bin", "op", "open", "close", "punct", "inner")
groups <- c(
  rel = "rel", bin = "bin", "op-token" = "op", open = "open",
  close = "close", punct = "punct", inner = "inner"
)

js_file <- list.files(
  system.file("js", package = "katex"),
  pattern = "^katex.*\\.js$",
  full.names = TRUE
)[1]
js <- paste(readLines(js_file, warn = FALSE, encoding = "UTF-8"), collapse = "\n")

# names given by the minifier to the strings "math", "main", "ams" and to the
# groups
decl <- regmatches(js, gregexpr("\\b\\w+=\"[a-z-]+\"", js))[[1]]
decl_name <- sub("=.*", "", decl)
decl_value <- gsub(".*=\"|\"", "", decl)
var_of <- function(value) unique(decl_name[decl_value == value])
math_var <- var_of("math")
font_vars <- c(var_of("main"), var_of("ams"))
group_vars <- unlist(lapply(names(groups), function(g) {
  v <- var_of(g)
  stats::setNames(rep(groups[[g]], length(v)), v)
}))

str_re <- "\"((?:[^\"\\\\]|\\\\.)*)\""
call_re <- paste0(
  "\\b\\w+\\((", paste(math_var, collapse = "|"), "),(",
  paste(font_vars, collapse = "|"), "),(\\w+),", str_re, ",", str_re
)
calls <- regmatches(js, gregexpr(call_re, js, perl = TRUE))[[1]]
parts <- regmatches(calls, regexec(call_re, calls, perl = TRUE))
group <- vapply(parts, `[`, "", 4)
char <- vapply(parts, `[`, "", 5)

# JavaScript escapes of the characters (\u2227, \xb1, \\, \")
js_unescape <- function(x) {
  vapply(x, function(s) {
    m <- gregexpr("\\\\u[0-9a-fA-F]{4}|\\\\x[0-9a-fA-F]{2}|\\\\.", s)
    regmatches(s, m) <- lapply(regmatches(s, m), function(e) {
      hex <- grepl("^\\\\[ux]", e) & nchar(e) > 2
      ifelse(hex, intToUtf8(strtoi(substring(e, 3), 16L), multiple = TRUE), substring(e, 2))
    })
    s
  }, "", USE.NAMES = FALSE)
}
char <- js_unescape(char)
keep <- group %in% names(group_vars) & nchar(char) == 1
cls <- unname(group_vars[group[keep]])
char <- char[keep]

# relations written by macros of KaTeX, not in the table of symbols (\neq,
# \notin)
char <- c(char, intToUtf8(c(0x2260, 0x2209), multiple = TRUE))
cls <- c(cls, "rel", "rel")

classes <- tapply(cls, char, function(x) priority[min(match(x, priority))])
classes <- classes[order(utf8ToInt(paste(names(classes), collapse = "")))]

# R code, ASCII only
r_string <- function(ch) {
  cp <- utf8ToInt(ch)
  if (cp < 128) {
    paste0("\"", gsub("([\"\\\\])", "\\\\\\1", ch), "\"")
  } else {
    sprintf("\"\\u%04X\"", cp)
  }
}
entries <- sprintf("  %s = \"%s\"", vapply(names(classes), r_string, ""), classes)
out <- c(
  "# Generated by data-raw/math_classes.R from the table of symbols of KaTeX",
  sprintf("# %s: do not edit by hand.", basename(js_file)),
  "#",
  "# TeX class of the characters of <mo> elements: \"bin\" (binary operator),",
  "# \"rel\" (relation), \"op\" (large operator), \"open\", \"close\", \"punct\"",
  "# (punctuation) and \"inner\"; the others are ordinary atoms.",
  "math_classes <- c(",
  paste0(entries, c(rep(",", length(entries) - 1), "")),
  ")"
)
writeLines(out, "R/math_classes.R")
